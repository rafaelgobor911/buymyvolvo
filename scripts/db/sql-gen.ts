/**
 * Pure SQL generators (no DB access) for:
 *  - the taxonomy data migration (from src/lib/taxonomy/data.ts)
 *  - supabase/seed.sql (fictitious listings, dev only)
 * `npm run db:generate` writes both files; a unit test keeps them in sync.
 */
import { formatInteger, listingSlug } from "@/lib/listings/format";
import {
  ENGINES,
  getEngine,
  getModel,
  getTrim,
  MODELS,
  modelYearRange,
  TRANSMISSION_LABELS,
  TRIMS,
} from "@/lib/taxonomy";

import { FIXTURE_LISTINGS, FIXTURE_SELLERS, type FixtureListing } from "./fixtures";

export const TAXONOMY_MIGRATION = "supabase/migrations/20261107120400_taxonomy_data.sql";
export const SEED_FILE = "supabase/seed.sql";

const lit = (value: string | number | boolean | null | undefined): string => {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return `'${value.replace(/'/g, "''")}'`;
};
const arr = (values: readonly string[] | null | undefined): string =>
  values == null
    ? "null"
    : values.length === 0
      ? "'{}'::text[]"
      : `array[${values.map(lit).join(", ")}]`;
const review = (note: string | undefined) => (note ? ` -- REVISAR: ${note}` : "");

function rows(items: string[][], notes: Array<string | undefined>): string {
  return items
    .map((cols, i) => `  (${cols.join(", ")})${i < items.length - 1 ? "," : ""}${review(notes[i])}`)
    .join("\n");
}

export function generateTaxonomySql(): string {
  const out: string[] = [
    "-- GENERATED by `npm run db:generate` from src/lib/taxonomy/data.ts. Do not edit by hand.",
    "-- Idempotent upserts: after go-live, regenerate into a NEW migration instead of editing this one.",
    "-- Lines marked REVISAR need validation by the product owner.",
    "",
  ];

  out.push(
    "insert into public.vehicle_models",
    "  (id, name, body_types, aliases, parent_id, renamed_from_id, renamed_scope, year_start, year_end, sort_order, review_note)",
    "values",
    rows(
      MODELS.map((m, i) => {
        const { start, end } = modelYearRange(m);
        return [
          lit(m.id),
          lit(m.name),
          arr(m.bodyTypes),
          arr(m.aliases),
          lit(m.parentId),
          lit(m.renamedFrom?.modelId),
          lit(m.renamedFrom?.scope),
          lit(start),
          lit(end),
          lit(i + 1),
          lit(m.review),
        ];
      }),
      MODELS.map((m) => m.review),
    ),
    "on conflict (id) do update set name = excluded.name, body_types = excluded.body_types,",
    "  aliases = excluded.aliases, parent_id = excluded.parent_id, renamed_from_id = excluded.renamed_from_id,",
    "  renamed_scope = excluded.renamed_scope, year_start = excluded.year_start, year_end = excluded.year_end,",
    "  sort_order = excluded.sort_order, review_note = excluded.review_note;",
    "",
  );

  const generations = MODELS.flatMap((m) => m.generations.map((g) => ({ m, g })));
  out.push(
    "insert into public.vehicle_generations (id, model_id, name, year_start, year_end, platform, review_note)",
    "values",
    rows(
      generations.map(({ m, g }) => [
        lit(g.id),
        lit(m.id),
        lit(g.name),
        lit(g.yearStart),
        lit(g.yearEnd),
        lit(g.platform),
        lit(g.review),
      ]),
      generations.map(({ g }) => g.review),
    ),
    "on conflict (id) do update set model_id = excluded.model_id, name = excluded.name,",
    "  year_start = excluded.year_start, year_end = excluded.year_end, platform = excluded.platform,",
    "  review_note = excluded.review_note;",
    "",
  );

  out.push(
    "insert into public.vehicle_engines (id, name, fuels, platforms, model_ids, aliases, year_start, year_end, review_note)",
    "values",
    rows(
      ENGINES.map((e) => [
        lit(e.id),
        lit(e.name),
        arr(e.fuels),
        arr(e.platforms),
        arr(e.modelIds ?? null),
        arr(e.aliases),
        lit(e.yearStart),
        lit(e.yearEnd),
        lit(e.review),
      ]),
      ENGINES.map((e) => e.review),
    ),
    "on conflict (id) do update set name = excluded.name, fuels = excluded.fuels, platforms = excluded.platforms,",
    "  model_ids = excluded.model_ids, aliases = excluded.aliases, year_start = excluded.year_start,",
    "  year_end = excluded.year_end, review_note = excluded.review_note;",
    "",
  );

  out.push(
    "insert into public.vehicle_trims (id, name, model_ids, engine_ids, aliases, year_start, year_end, review_note)",
    "values",
    rows(
      TRIMS.map((t) => [
        lit(t.id),
        lit(t.name),
        arr(t.modelIds ?? null),
        arr(t.engineIds ?? null),
        arr(t.aliases),
        lit(t.yearStart),
        lit(t.yearEnd),
        lit(t.review),
      ]),
      TRIMS.map((t) => t.review),
    ),
    "on conflict (id) do update set name = excluded.name, model_ids = excluded.model_ids,",
    "  engine_ids = excluded.engine_ids, aliases = excluded.aliases, year_start = excluded.year_start,",
    "  year_end = excluded.year_end, review_note = excluded.review_note;",
    "",
  );

  return out.join("\n");
}

// --- Seed (fictitious listings) ---------------------------------------------

export const fixtureListingId = (index: number) =>
  `00000000-0000-4000-8000-${String(index + 1).padStart(12, "0")}`;
export const fixtureSellerId = (index: number) =>
  `00000000-0000-4000-9000-${String(index + 1).padStart(12, "0")}`;

export function fixtureSlug(listing: FixtureListing, index: number): string {
  return listingSlug(
    {
      modelName: getModel(listing.model)!.name,
      engineName: listing.engine ? getEngine(listing.engine)!.name : null,
      trimName: listing.trim ? getTrim(listing.trim)!.name : null,
      yearModel: listing.yearModel,
      city: listing.city,
      uf: listing.uf,
    },
    `d${index + 1}`,
  );
}

const FUEL_PHRASE: Record<FixtureListing["fuel"], string> = {
  gasolina: "motor a gasolina",
  diesel: "motor diesel",
  hibrido_leve: "híbrido leve",
  hibrido_plugin: "híbrido plug-in",
  eletrico: "100% elétrico",
};

/** Our own words, from structured fields only (mirrors what the AI summary will do). */
export function fixtureSummary(l: FixtureListing): string {
  const head = [
    getModel(l.model)!.name,
    l.engine ? getEngine(l.engine)!.name : null,
    l.trim ? getTrim(l.trim)!.name : null,
  ]
    .filter(Boolean)
    .join(" ");
  const seller = l.sellerType === "loja" ? "uma loja" : "um particular";
  const options = l.options.length > 0 ? ` Destaques: ${l.options.join(", ")}.` : "";
  return (
    `${head} ${l.yearFab}/${l.yearModel}, ${l.color}, com ${formatInteger(l.km)} km, ` +
    `câmbio ${TRANSMISSION_LABELS[l.transmission].toLowerCase()}, ${FUEL_PHRASE[l.fuel]}. ` +
    `Anunciado por ${seller} em ${l.city} (${l.uf}).${options}`
  );
}

